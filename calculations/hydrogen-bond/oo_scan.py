#!/usr/bin/env python3
"""Relaxed two-atom distance scans of a stored ECCE-QM example, run through ECCE.

    ECCE_SRC=<checkout> ECCE_TEST_HOME=<install>/ecce ECCE_TEST_WRAPPERS=<install>/bin \\
        python3 oo_scan.py <out dir> <example> <atom I> <atom J> <name:steps:step> [...]
        [--data DIR] [--calc NAME] [--post-only] [--timeout S]

<example> is the folder under data/client/examples, e.g.
genchem/intermolecular-interactions/ecceqm-h2o_dimer. The stored calculation in its
stored/ folder is copied once per scan into an isolated local data folder (--data,
kept), set to run type Geometry with a scan constraint on atoms I J (Builder
Geometry Constraints), its input generated by the Calculation Editor and launched
on localhost through the Launcher. Each scan is NAME:STEPS:STEP (STEP in Angstrom,
negative to go inward). When all have finished, each calculation's Relaxed Scan
panel is exported to <out>/<NAME>.csv and drawn on white to <out>/<NAME>.png.

While waiting, an Organizer stays open and reconnects (Run Mgmt > Reconnect)
any scan whose job monitor has gone, so a job outlives the Launcher that
started it. --post-only does the same for scans left Waiting, then exports.
"""
import argparse, glob, os, re, shutil, subprocess, sys, time
REPO = os.environ.get("ECCE_SRC", "ECCE")
sys.path.insert(0, os.path.join(REPO, "tests", "apps"))
import apps, isolate, xdisplay  # noqa: E402
import ecceqm_builder_test as eb  # noqa: E402
import md_compare_examples_test as mc  # noqa: E402

ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
ap.add_argument("out")
ap.add_argument("example")
ap.add_argument("atoms", nargs=2, type=int)
ap.add_argument("scans", nargs="+")
ap.add_argument("--data", default=None)
ap.add_argument("--calc", default=None)
ap.add_argument("--post-only", action="store_true")
ap.add_argument("--timeout", type=int, default=6 * 3600)
A = ap.parse_args()
OUT = os.path.abspath(A.out)
os.makedirs(OUT, exist_ok=True)
STUDY = A.example.rstrip("/").split("/")[-1]
DATA = os.path.abspath(A.data or os.path.join(os.path.expanduser("~"), "tmp", "ecce", "oo-scan-data", STUDY))
SCANS = []
for s in A.scans:
    n, steps, step = s.split(":")
    SCANS.append((n, int(steps), float(step)))


def meta_set(path, key, value):
    text = open(path, errors="surrogateescape").read()
    text = re.sub(r"(ecce:%s\t\t)[^\n]*" % key, lambda m: m.group(1) + value, text)
    open(path, "w", errors="surrogateescape").write(text)


def meta_get(path, key):
    m = re.search(r"ecce:%s\t\t([^\n]*)" % key, open(path, errors="surrogateescape").read())
    return m.group(1) if m else ""


TERMINAL = ("Complete", "Completed", "Failed", "Killed", "Unsuccessful", "Loaded")


def monitor_alive(rundir):
    """True if an eccejobmonitor runs in rundir (its working directory)."""
    for p in glob.glob("/proc/[0-9]*"):
        try:
            if "eccejobmonitor" in open(p + "/cmdline", "rb").read().decode(errors="replace") \
                    and os.path.realpath(os.readlink(p + "/cwd")) == os.path.realpath(rundir):
                return True
        except OSError:
            pass
    return False


class Organizer:
    """An Organizer kept open while the jobs run, driven through ECCE_TEST_ORGANIZER.

    A reconnected job monitor reports to the process that reconnected it, so
    this one must outlive the jobs."""

    def __init__(self, display):
        self.script = os.path.join(DATA, "organizer.script")
        open(self.script, "w").close()
        self.log = open(os.path.join(OUT, "organizer.log"), "w")
        env = display.env()
        env.update(ECCE_TEST_ORGANIZER=self.script, ECCE_FEEDBACK_STDERR="1")
        self.proc = subprocess.Popen([os.path.join(apps.WRAPPERS, "ecce-organizer")], env=env,
                                     stdout=self.log, stderr=subprocess.STDOUT, start_new_session=True)
        time.sleep(30)

    def send(self, line):
        open(self.script, "a").write(line + "\n")

    def close(self):
        apps._terminate(self.proc)
        self.log.close()


def wait_for_jobs(display, root):
    """Poll the stored states until every scan is terminal, reconnecting lost monitors."""
    states = lambda: {n: meta_get(os.path.join(root, n, ".ecce-meta"), "state") for n, _, _ in SCANS}
    if all(v in TERMINAL for v in states().values()):
        return
    org = Organizer(display)
    lost = {}
    try:
        end = time.time() + A.timeout
        while time.time() < end:
            st = states()
            print(time.strftime("%H:%M:%S"), st, flush=True)
            if all(v in TERMINAL for v in st.values()):
                break
            for n, v in st.items():
                rundir = os.path.join(DATA, "run-" + n, "qm", n)
                if v in TERMINAL or v in ("Created", "Ready") or monitor_alive(rundir):
                    lost.pop(n, None)
                    continue
                # Two polls without a monitor: the launching side has gone.
                lost[n] = lost.get(n, 0) + 1
                if lost[n] == 2:
                    print(n, "no job monitor; reconnecting", flush=True)
                    org.send("reconnectjob file://" + os.path.join(root, n) + "/")
                elif lost[n] > 6:
                    lost[n] = 0
            time.sleep(60)
    finally:
        org.close()


def app(display, name, var, lines, url, extra=None, panel=None, settle=60, wt=90):
    script = os.path.join(DATA, "%s.script" % name)
    open(script, "w").write("\n".join(lines) + "\n")
    env = {var: script, "ECCE_FEEDBACK_STDERR": "1"}
    env.update(extra or {})
    if panel:
        env.update(ECCE_PANEL_MODE="detail", ECCE_OPEN_PANEL=panel)
    r = apps.run(display, name, args=["-context", url], windowTimeout=wt, settle=settle, env=env)
    open(os.path.join(OUT, "%s-%s.log" % (os.path.basename(url.rstrip("/")), name)), "w").write(r.log or "")
    return r.log or ""


def main():
    isolate.apply(apps.INSTALL)
    os.environ.update(ECCE_NO_REAP="1", GTK_THEME="Adwaita",
                      GDK_DPI_SCALE=os.environ.get("DPI", "1.5"))
    exdir = os.path.join(REPO, "data", "client", "examples", A.example, "stored")
    calc = A.calc or sorted(os.listdir(exdir))[0]
    i, j = A.atoms
    root = os.path.join(DATA, "users", "local", "qm")
    if not A.post_only:
        shutil.rmtree(DATA, ignore_errors=True)
        os.makedirs(root)
        shutil.copy(eb.PROJECT_META, os.path.join(root, ".ecce-meta"))
        for n, steps, step in SCANS:
            d = os.path.join(root, n)
            shutil.copytree(os.path.join(exdir, calc), d, symlinks=True)
            for sub in ("Props", "Outputs"):
                for f in glob.glob(os.path.join(d, sub, "*")):
                    (shutil.rmtree if os.path.isdir(f) else os.remove)(f)
            # Stored examples ship without Inputs/; without it Save fails
            # ("input file copy to DAV failed").
            os.makedirs(os.path.join(d, "Inputs"), exist_ok=True)
            # The stored example's SetupParams lacks the D3(BJ) tick that its
            # hand-written .qmin has; add it so the scan uses B3LYP-D3(BJ).
            sp = os.path.join(d, "Parameters", "SetupParams")
            if "ES.Theory.ECCEQM.Dispersion|" not in open(sp).read():
                open(sp, "a").write("ES.Theory.ECCEQM.Dispersion|1||1|1|toggle_input\n")
            g = os.path.join(d, "Parameters", "GeomConstraintModel.gcst")
            if os.path.exists(g):
                os.remove(g)
            m = os.path.join(d, ".ecce-meta")
            meta_set(m, "state", "Ready"); meta_set(m, "runtype", "Geometry")
            meta_set(m, "launch_machine", "localhost")
            meta_set(m, "annotation", "Relaxed scan of atoms %d-%d, %d steps of %g A" % (i, j, steps, step))
    os.environ["ECCE_LOCAL_DATA"] = DATA
    xdisplay.SCREEN = "1500x950x24"
    with xdisplay.Display() as display:
        subprocess.run([os.path.join(apps.INSTALL, "bin", "ecce-gateway-start")], env=display.env(), timeout=180)
        try:
            if not A.post_only:
                for n, steps, step in SCANS:
                    url = "file://" + os.path.join(root, n) + "/"
                    log = app(display, "builder", "ECCE_BUILDER_SCRIPT",
                              ["wait 4000", "constraints select %d %d" % (i, j),
                               "constraints scan %d %g yes" % (steps, step), "constraints list", "save",
                               "wait 2500", "constraints stored", "wait 500", "quit"], url)
                    print(n, "\n".join(l for l in log.splitlines() if "constraint" in l or "FAIL" in l))
                    log = app(display, "calced", "ECCE_CALCED_SCRIPT",
                              # No "ready": a stored calc that already holds theory values starts
                              # no theory dialog, so "ready" would wait forever.
                              ["wait 8000", "runtype Geometry", "wait 6000", "button save",
                               "wait 6000", "info", "quit"], url)
                    print(n, "\n".join(l for l in log.splitlines() if "CALCED" in l or "FAIL" in l)[-800:])
                    qmin = glob.glob(os.path.join(root, n, "Inputs", "*.qmin"))
                    if not qmin:
                        sys.exit("no input generated for " + n)
                    shutil.copy(qmin[0], os.path.join(OUT, n + ".qmin"))
                    print(n, "input:", [l for l in open(qmin[0]).read().splitlines()
                                        if re.match(r"(runtype|scan|constraint|opt|method|dispersion|basis)", l.strip())])
                    run = os.path.join(DATA, "run-" + n)
                    os.makedirs(run, exist_ok=True)
                    log = app(display, "launcher", "ECCE_LAUNCHER_SCRIPT",
                              ["wait 3000", "machine localhost", "rundir " + run, "wait 1500", "launch",
                               "wait 8000", "quit"], url, settle=30)
                    print(n, "\n".join(l for l in log.splitlines() if "LAUNCHER" in l or "FAIL" in l)[-600:])
            wait_for_jobs(display, root)
            for n, steps, step in SCANS:
                url = "file://" + os.path.join(root, n) + "/"
                scene = os.path.join(DATA, "scene-" + n)
                os.environ["ECCE_VIEWER_SCENE_OUT"] = OUT
                open(scene, "w").write("background 1 1 1\nhold 10\nplotshot %s 1000 820 Relaxed Scan\nhold 2\n" % n)
                os.environ["ECCE_VIEWER_SCENE"] = scene
                log = mc.builder(display, url, ["wait 12000", "scancsv %s/%s.csv" % (OUT, n), "wait 25000"],
                                 settle=90, panel="Relaxed Scan")
                print(n, "\n".join(l for l in log.splitlines() if any(k in l for k in ("scancsv", "PLOTSHOT", "FAIL")))[-800:])
        finally:
            subprocess.run([os.path.join(apps.INSTALL, "bin", "ecce-gateway-stop")], env=display.env(), timeout=120)
    print("out:", sorted(os.listdir(OUT)), "data kept:", DATA)


if __name__ == "__main__":
    main()
